// Dependency gate (meta#103, decision 23 "Accepted costs"): the mitigation the npm dependency risk is accepted on,
// in the one service that holds a credential. Three layers, all failing CI:
//
//  1. DIRECT dependencies: package.json's dependencies and devDependencies are exactly the names in the matching
//     section of allowed-dependencies.txt; a name moved between sections fails. Every spec is a plain semver range
//     (no npm: alias, git, file or URL spec) except the one release tarball admitted below.
//  2. EVERY package in package-lock.json, direct or transitive: it must be in dependency-snapshot.txt, with the same
//     version and sha512 integrity, in the same section ([runtime]: what `npm ci --omit=dev` installs and the image
//     ships; [dev]: everything else), and the snapshot may hold nothing the lockfile no longer has. A new transitive
//     package is therefore a visible diff in a reviewed pull request, never a silent arrival: adding or upgrading
//     anything means `npm run snapshot:deps` and committing the result. The runtime section is the one to read.
//  3. The lockfile's shape: every `resolved` is exactly the registry's URL for the entry's name and version
//     (https://registry.npmjs.org/<name>/-/<basename>-<version>.tgz, so no `..` or other package rides on it), or (for
//     the one named package) its GitHub release tarball; one name@version with two integrities is refused, not merged; sha512 integrity everywhere; no entry installed under another name than its
//     path (bar the pinned aliases npm writes for jest); no overrides/resolutions, bundled dependencies or .npmrc;
//     and nothing in the runtime section that installs code outside the registry's tarball: no install script, no
//     platform-specific binary (the image build also fails on a compiled file in the production tree).
//
//   node scripts/check-dependencies.cjs                    check
//   node scripts/check-dependencies.cjs --write-snapshot   rewrite dependency-snapshot.txt from package-lock.json
const fs = require("fs");
const path = require("path");

// The release tarballs admitted, by package name. @v-m-pioneer-trading/eslint-config lives in devDependencies; its
// URL must name the same version twice (the tag and the file).
const TARBALLS = {
  "@v-m-pioneer-trading/eslint-config": {
    section: "devDependencies",
    url: /^https:\/\/github\.com\/V-M-Pioneer-Trading\/eslint-config\/releases\/download\/v([0-9]+\.[0-9]+\.[0-9]+)\/v-m-pioneer-trading-eslint-config-\1\.tgz$/,
  },
};
const SEMVER_RANGE = /^[~^]?[0-9]+\.[0-9]+\.[0-9]+$/;
// The aliases npm itself writes for jest's tree (react-is, string-width and friends under another name).
// Pinned by lock path, name and version: a new alias, or a changed one, is a reviewed diff here.
const KNOWN_ALIASES = {
  "node_modules/@jest/react-is-18": { name: "react-is", version: "18.3.1" },
  "node_modules/@jest/react-is-19": { name: "react-is", version: "19.3.0" },
  "node_modules/string-width-cjs": { name: "string-width", version: "4.2.3" },
  "node_modules/strip-ansi-cjs": { name: "strip-ansi", version: "6.0.1" },
  "node_modules/wrap-ansi-cjs": { name: "wrap-ansi", version: "7.0.0" },
};
const SECTIONS = ["dependencies", "devDependencies"];
const SNAPSHOT_SECTIONS = ["runtime", "dev"];
const SNAPSHOT_HEADER = `# Transitive dependency snapshot (meta#103, decision 23). Generated by \`npm run snapshot:deps\` from
# package-lock.json; scripts/check-dependencies.cjs fails CI when the lockfile and this file differ in any way.
# One line per package: name@version and its sha512 integrity. [runtime] is what \`npm ci --omit=dev\` installs and the
# image ships; [dev] is everything else (build, test, lint). A package that appears here is a package a reviewer saw.
`;

function parseAllowlist(text) {
  const out = { dependencies: new Set(), devDependencies: new Set() };
  let section = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*/, "").trim();
    if (line === "") continue;
    const m = /^\[(\w+)\]$/.exec(line);
    if (m) {
      if (!SECTIONS.includes(m[1])) throw new Error(`allowed-dependencies.txt: unknown section [${m[1]}]`);
      section = m[1];
    } else if (section === null) {
      throw new Error(`allowed-dependencies.txt: "${line}" is outside a [dependencies] / [devDependencies] section`);
    } else {
      out[section].add(line);
    }
  }
  return out;
}

/** The name a lock path installs: what follows its last node_modules/. */
const nameOfPath = (where) => where.slice(where.lastIndexOf("node_modules/") + "node_modules/".length);

/**
 * Which snapshot section a lockfile entry belongs to. Only `dev: true` is never installed with --omit=dev:
 * `devOptional` (a dev dependency that is also an optional one of something that ships) IS installed, so it is runtime.
 */
const sectionOfEntry = (entry) => (entry.dev === true ? "dev" : "runtime");

/** The snapshot of a lockfile: Map "section name@version" -> integrity. The name is the installed one (aliases keep their path name). */
function computeSnapshot(lock) {
  const out = new Map();
  for (const [where, entry] of Object.entries(lock.packages ?? {})) {
    if (where === "") continue;
    const name = entry.name ?? nameOfPath(where);
    const key = `${sectionOfEntry(entry)} ${name}@${entry.version}`;
    // A second copy of the same name@version keeps the first's integrity: a different one is reported by snapshotConflicts.
    if (!out.has(key)) out.set(key, entry.integrity ?? "(no integrity)");
  }
  return out;
}

/**
 * The same name@version in one section with different integrity at two lock paths: the snapshot line can hold only
 * one, and a silent overwrite would let a substituted package hide behind an honest copy.
 */
function snapshotConflicts(lock) {
  const seen = new Map();
  const problems = [];
  for (const [where, entry] of Object.entries(lock.packages ?? {})) {
    if (where === "") continue;
    const name = entry.name ?? nameOfPath(where);
    const key = `${sectionOfEntry(entry)} ${name}@${entry.version}`;
    const integrity = entry.integrity ?? "(no integrity)";
    const first = seen.get(key);
    if (first === undefined) seen.set(key, { where, integrity });
    else if (first.integrity !== integrity) {
      problems.push(`package-lock.json: ${name}@${entry.version} has different integrity at ${first.where} and at ${where}: one name and version, two sets of bytes`);
    }
  }
  return problems;
}

const SEMVER_VERSION = /^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?(\+[0-9A-Za-z.-]+)?$/;

/** The one URL the registry serves a package's tarball from: scoped names keep their scope in the path only. */
function registryTarball(name, version) {
  return `https://registry.npmjs.org/${name}/-/${name.slice(name.lastIndexOf("/") + 1)}-${version}.tgz`;
}

function renderSnapshot(snapshot) {
  let text = SNAPSHOT_HEADER;
  for (const section of SNAPSHOT_SECTIONS) {
    text += `\n[${section}]\n`;
    const lines = [...snapshot.entries()]
      .filter(([key]) => key.startsWith(`${section} `))
      .map(([key, integrity]) => `${key.slice(section.length + 1)} ${integrity}`)
      .sort();
    for (const line of lines) text += `${line}\n`;
  }
  return text;
}

function parseSnapshot(text) {
  const out = new Map();
  let section = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line === "" || line.startsWith("#")) continue;
    const m = /^\[(\w+)\]$/.exec(line);
    if (m) {
      if (!SNAPSHOT_SECTIONS.includes(m[1])) throw new Error(`dependency-snapshot.txt: unknown section [${m[1]}]`);
      section = m[1];
      continue;
    }
    if (section === null) throw new Error(`dependency-snapshot.txt: "${line}" is outside a [runtime] / [dev] section`);
    const parts = line.split(/\s+/);
    if (parts.length !== 2) throw new Error(`dependency-snapshot.txt: "${line}" is not "name@version integrity"`);
    const key = `${section} ${parts[0]}`;
    if (out.has(key)) throw new Error(`dependency-snapshot.txt: ${parts[0]} is listed twice in [${section}]`);
    out.set(key, parts[1]);
  }
  return out;
}

/** The problems of a snapshot against a lockfile: what the lockfile gained, lost or changed. */
function snapshotProblems(lock, snapshotText) {
  const problems = [];
  let committed;
  try {
    committed = parseSnapshot(snapshotText);
  } catch (err) {
    return [err.message];
  }
  const actual = computeSnapshot(lock);
  const label = (key) => {
    const space = key.indexOf(" ");
    return `${key.slice(space + 1)} [${key.slice(0, space)}]`;
  };
  for (const [key, integrity] of actual) {
    if (!committed.has(key)) {
      problems.push(`package-lock.json gained ${label(key)}, which is not in dependency-snapshot.txt: review it, then run "npm run snapshot:deps"`);
    } else if (committed.get(key) !== integrity) {
      problems.push(`${label(key)} has a different integrity in package-lock.json than in dependency-snapshot.txt (same version, other bytes)`);
    }
  }
  for (const key of committed.keys()) {
    if (!actual.has(key)) problems.push(`dependency-snapshot.txt lists ${label(key)}, which package-lock.json no longer has: run "npm run snapshot:deps"`);
  }
  return problems;
}

function check(pkg, lock, allowlistText, snapshotText, opts = {}) {
  const allowed = parseAllowlist(allowlistText);
  const problems = [];
  if (lock.lockfileVersion !== 3) problems.push(`package-lock.json has lockfileVersion ${lock.lockfileVersion}; only 3 is checked`);
  for (const extra of ["optionalDependencies", "peerDependencies"]) {
    const v = pkg[extra];
    if (v !== undefined && Object.keys(v).length > 0) problems.push(`package.json has ${extra}; only dependencies and devDependencies are allowed`);
  }
  // Any truthy form, `true` included: bundled packages are installed from the tarball itself.
  for (const key of ["bundledDependencies", "bundleDependencies"]) {
    if (pkg[key]) problems.push(`package.json has ${key}; bundled dependencies are not allowed`);
  }
  // These rewrite what a name resolves to (overrides: {"body-parser": "npm:left-pad@1"}).
  for (const key of ["overrides", "resolutions"]) {
    if (key in pkg) problems.push(`package.json has ${key}; a name must resolve to itself`);
  }
  // A workspace makes local directories packages, installed from disk with no registry or integrity behind them.
  if ("workspaces" in pkg) problems.push("package.json has workspaces; local packages are not admitted");
  if (opts.npmrc) problems.push(".npmrc exists; it can redirect the registry or alias packages. Configure nothing there");
  const lockRoot = lock.packages?.[""] ?? {};
  for (const section of SECTIONS) {
    const declared = pkg[section] ?? {};
    for (const [name, spec] of Object.entries(declared)) {
      if (!allowed[section].has(name)) problems.push(`${name} is in ${section} but not in the [${section}] section of allowed-dependencies.txt`);
      const tarball = TARBALLS[name];
      if (tarball !== undefined) {
        if (section !== tarball.section || !tarball.url.test(spec)) {
          problems.push(`${name} must be its GitHub release tarball URL (https://github.com/V-M-Pioneer-Trading/..., the version in the tag and the file name equal) in ${tarball.section}`);
        }
      } else if (!SEMVER_RANGE.test(spec)) {
        problems.push(`${name}: "${spec}" is not a plain semver range (no npm: alias, git, file or URL spec)`);
      }
      if (name === "express" && !/^[~^]?4\./.test(spec)) problems.push("express must stay on major version 4 (the other TypeScript services and tsoa's generated routes target Express 4)");
      if (!(name in (lockRoot[section] ?? {}))) problems.push(`${name} is in ${section} but not in package-lock.json's root ${section}: run npm install`);
    }
    for (const name of allowed[section]) if (!(name in declared)) problems.push(`${name} is on the [${section}] allowlist but is not in ${section} (remove it)`);
    for (const name of Object.keys(lockRoot[section] ?? {})) if (!(name in declared)) problems.push(`${name} is in package-lock.json's root ${section} but not in package.json`);
  }
  for (const [where, entry] of Object.entries(lock.packages ?? {})) {
    if (where === "") continue;
    const pathName = nameOfPath(where);
    const alias = KNOWN_ALIASES[where];
    if (entry.name !== undefined && entry.name !== pathName) {
      if (alias === undefined || alias.name !== entry.name || alias.version !== entry.version) {
        problems.push(`package-lock.json: ${where} is installed as "${entry.name}" under another name; only the pinned aliases are allowed`);
      }
    } else if (alias !== undefined && entry.version !== alias.version) {
      problems.push(`package-lock.json: ${where} is not the pinned alias ${alias.name}@${alias.version}`);
    }
    const resolved = entry.resolved;
    // A link is a package that is a directory on disk (a workspace, a file: dependency): never admitted.
    if (entry.link) problems.push(`package-lock.json: ${where} is a link (link: true); a package must come from the registry`);
    if (resolved === undefined) {
      if (!entry.link) problems.push(`package-lock.json: ${where} has no resolved URL`);
      continue;
    }
    const installedAs = entry.name ?? pathName;
    const tarball = TARBALLS[installedAs];
    const isRelease = tarball !== undefined && tarball.url.test(resolved);
    if (isRelease) {
      // The release URL is for its package alone, and only where the manifest asked for it.
      if (where !== `node_modules/${installedAs}`) problems.push(`package-lock.json: ${where} resolves from the ${installedAs} release tarball but is not at the top level`);
    } else if (!resolved.startsWith("https://registry.npmjs.org/")) {
      problems.push(`package-lock.json: ${where} resolves from ${resolved}, which is neither registry.npmjs.org nor an admitted release tarball`);
    } else if (typeof entry.version !== "string" || !SEMVER_VERSION.test(entry.version)) {
      problems.push(`package-lock.json: ${where} has a version that is not plain semver: ${JSON.stringify(entry.version)}`);
    } else if (resolved !== registryTarball(installedAs, entry.version)) {
      // Exactly the registry's URL for this name and version, so a path of ".." or a URL of another package or version
      // cannot ride on an honest name and version (npm ci installs what resolved says, not what the entry says).
      problems.push(`package-lock.json: ${where} is "${installedAs}@${entry.version}" but resolves from ${resolved}, not ${registryTarball(installedAs, entry.version)}`);
    }
    if (!/^sha512-[A-Za-z0-9+/]+=*$/.test(entry.integrity ?? "")) problems.push(`package-lock.json: ${where} has no sha512 integrity`);
    // The runtime tree is what the image ships: nothing that runs code at install time or is built per platform.
    if (sectionOfEntry(entry) === "runtime") {
      if (entry.hasInstallScript) problems.push(`package-lock.json: runtime package ${where} has an install script`);
      if (entry.os !== undefined || entry.cpu !== undefined || entry.libc !== undefined) problems.push(`package-lock.json: runtime package ${where} is platform-specific (os/cpu): a native binary`);
      if (entry.optional === true) problems.push(`package-lock.json: runtime package ${where} is optional`);
    }
  }
  problems.push(...snapshotConflicts(lock));
  problems.push(...snapshotProblems(lock, snapshotText));
  return problems;
}

module.exports = { check, parseAllowlist, snapshotConflicts, registryTarball, computeSnapshot, renderSnapshot, parseSnapshot, snapshotProblems, KNOWN_ALIASES };

if (require.main === module) {
  const root = path.join(__dirname, "..");
  const read = (f) => fs.readFileSync(path.join(root, f), "utf8");
  const lock = JSON.parse(read("package-lock.json"));
  if (process.argv.includes("--write-snapshot")) {
    // Written LF whatever the platform, so the committed file is the same bytes everywhere.
    fs.writeFileSync(path.join(root, "dependency-snapshot.txt"), renderSnapshot(computeSnapshot(lock)));
    console.log(`dependency-snapshot.txt: ${computeSnapshot(lock).size} packages. Review the diff.`);
    process.exit(0);
  }
  const pkg = JSON.parse(read("package.json"));
  const problems = check(pkg, lock, read("allowed-dependencies.txt"), read("dependency-snapshot.txt"), { npmrc: fs.existsSync(path.join(root, ".npmrc")) });
  if (problems.length > 0) {
    for (const p of problems.slice(0, 60)) console.error(`::error file=ts/dependency-snapshot.txt::${p}`);
    if (problems.length > 60) console.error(`::error::... and ${problems.length - 60} more`);
    process.exit(1);
  }
  const snapshot = computeSnapshot(lock);
  const count = (section) => [...snapshot.keys()].filter((k) => k.startsWith(`${section} `)).length;
  console.log(
    `${Object.keys(pkg.dependencies ?? {}).length + Object.keys(pkg.devDependencies ?? {}).length} direct dependencies, all on the allowlist; ` +
      `${snapshot.size} packages in the lockfile, all in the snapshot (${count("runtime")} runtime, ${count("dev")} dev).`,
  );
}
