const NOW = 1_790_000_000;

const b64u = (bytes: string): string => Buffer.from(bytes, "latin1").toString("base64url");
const HEADER = b64u('{"alg":"RS256","typ":"JWT"}');
/** A token whose payload is the given JSON text (as bytes). */
const tok = (payload: string): string => `${HEADER}.${b64u(payload)}.c2ln`;
const claims = (iat: number | string, exp: number | string): string => tok(`{"iat":${String(iat)},"exp":${String(exp)}}`);

const deep = (n: number): string => `${"[".repeat(n)}${"]".repeat(n)}`;

