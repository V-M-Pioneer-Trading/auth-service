/** UTF-8 bytes of `s`, as a one-char-per-byte string. */
const u = (s: string): string => Buffer.from(s, "utf8").toString("latin1");
const cp = (...points: number[]): string => String.fromCodePoint(...points);

/** The clock the token cases are judged at: whole seconds, plus 400 ms, so `now.Unix()` truncates. */
